"""Gaussian one- and two-electron integral engine.

All quantities are in atomic units with coordinates in bohr.

Method
------
McMurchie-Davidson in the "polynomial-coefficient" form:

* a gaussian pair is expanded in Hermite gaussians, with E coefficients
  generated by the standard recursion;
* the Coulomb / nuclear-attraction interaction of two such expansions is
  obtained from *derivatives of the Boys function*,

      D_{nx,ny,nz} = d_X^{nx} d_Y^{ny} d_Z^{nz} F_0(rho R^2),

  represented symbolically as

      d_X^n F_0 = sum_u c[n][u] X^{2u-n} (2 rho)^u F_u .

  The integer table ``c[n][u]`` is generated once (see ``_deriv_table``).

Sign convention (verified against 3D numerical integration in
dev/test_integrals.py): the E recursion generates the expansion
    (x-A)^i (x-B)^j e^{-...} = sum_t E_t  d_P^t e^{-p(x-P)^2},
i.e. the Hermite basis is the *plain* derivative (no extra (-1)^t), so no sign
factor appears in the assembly.
"""

from __future__ import annotations

import numpy as np
from scipy.special import gammainc, gamma as _gamma

from .basis import CART_POWERS

TWO_PI_52 = 2.0 * np.pi ** 2.5

_CTAB: dict = {}


def boys(m: int, T) -> np.ndarray:
    """Boys function F_m(T) = int_0^1 t^{2m} exp(-T t^2) dt (vectorised)."""
    T = np.asarray(T, dtype=float)
    out = np.empty(T.shape, dtype=float)
    small = T <= 1e-14
    if small.any():
        out[small] = 1.0 / (2 * m + 1)
    big = ~small
    if big.any():
        Tb = T[big]
        out[big] = (0.5 * Tb ** (-(m + 0.5)) * gammainc(m + 0.5, Tb)
                    * _gamma(m + 0.5))
    return out


def _deriv_table(nmax: int):
    """Coefficients c[n][u] such that d_X^n F_0 = sum_u c X^{2u-n} (2rho)^u F_u."""
    if nmax in _CTAB:
        return _CTAB[nmax]
    exp = [dict() for _ in range(nmax + 1)]
    exp[0][(0, 0)] = 1
    for n in range(nmax):
        for (a, m), c in exp[n].items():
            if a > 0:
                exp[n + 1][(a - 1, m)] = exp[n + 1].get((a - 1, m), 0) + a * c
            exp[n + 1][(a + 1, m + 1)] = exp[n + 1].get((a + 1, m + 1), 0) - c
    tab = []
    for n in range(nmax + 1):
        d = {}
        for (a, m), c in exp[n].items():
            assert a == 2 * m - n, (a, m, n)
            d[m] = d.get(m, 0) + c
        tab.append(d)
    _CTAB[nmax] = tab
    return tab


def e_coeffs(l1: int, l2: int, p, XPA, XPB):
    """Hermite expansion coefficients E[i][j], shape ``p.shape + (l1+l2+1,)``."""
    W = l1 + l2 + 1
    inv2p = 0.5 / p
    arange = np.arange(1, W)

    def shift(E, X):
        out = np.zeros(E.shape[:-1] + (W,), dtype=float)
        out[..., 1:] = E[..., :W - 1] * inv2p[..., None]
        out += X[..., None] * E
        out[..., :W - 1] += arange * E[..., 1:W]
        return out

    E = [[None] * (l2 + 1) for _ in range(l1 + 1)]
    z = np.zeros(p.shape + (W,), dtype=float)
    z[..., 0] = 1.0
    E[0][0] = z
    for i in range(l1):
        E[i + 1][0] = shift(E[i][0], XPA)
    for j in range(l2):
        for i in range(l1 + 1):
            E[i][j + 1] = shift(E[i][j], XPB)
    return E


def _fold_bra(G, H, M):
    """out[..., m] = sum_{t+u=m} G[..., t] H[..., u]."""
    W1 = G.shape[-1]
    W2 = H.shape[-1]
    bshape = np.broadcast_shapes(G.shape[:-1], H.shape[:-1])
    out = np.zeros(bshape + (M,), dtype=float)
    for t in range(W1):
        gt = G[..., t]
        for u in range(W2):
            # bra derivatives act as d_P = +d_X, ket derivatives as d_Q = -d_X
            out[..., t + u] += gt * H[..., u] * (-1.0) ** u
    return out


def deriv_sum(Gx, Gy, Gz, rho, X, Y, Z):
    """sum_n Gx[nx] Gy[ny] Gz[nz] d_X^nx d_Y^ny d_Z^nz F_0(rho R^2).

    ``G*`` : (C, P, M); ``X, Y, Z`` : (P,); ``rho`` : (P,).  Returns (C, P).
    """
    nmx = Gx.shape[-1] - 1
    nmy = Gy.shape[-1] - 1
    nmz = Gz.shape[-1] - 1
    tab = _deriv_table(max(nmx, nmy, nmz))
    Xb, Yb, Zb = X[None, :], Y[None, :], Z[None, :]

    def build(G, nmax, coord):
        outs = []
        for u in range(nmax + 1):
            acc = 0.0
            for n in range(u, min(nmax, 2 * u) + 1):
                c = tab[n].get(u, 0.0)
                if c:
                    acc = acc + G[..., n] * (c * coord ** (2 * u - n))
            outs.append(acc)
        return outs

    Px = build(Gx, nmx, Xb)
    Py = build(Gy, nmy, Yb)
    Pz = build(Gz, nmz, Zb)

    Q: dict = {}
    for ux, a in enumerate(Px):
        for uy, b in enumerate(Py):
            for uz, c in enumerate(Pz):
                U = ux + uy + uz
                Q[U] = Q.get(U, 0.0) + a * b * c

    T = rho * (X ** 2 + Y ** 2 + Z ** 2)
    out = np.zeros(Gx.shape[:-1], dtype=float)
    for U, val in Q.items():
        out = out + val * (2.0 * rho) ** U * boys(U, T)[None, :]
    return out


class IntegralEngine:
    """One- and two-electron integrals for a :class:`basis.Molecule`."""

    def __init__(self, mol):
        self.mol = mol
        self._pairs: dict = {}

    # ------------------------------------------------------------------
    def pair(self, i: int, j: int) -> dict:
        key = (i, j)
        if key in self._pairs:
            return self._pairs[key]
        s1, s2 = self.mol.shells[i], self.mol.shells[j]
        A, B = s1.center, s2.center
        al = s1.exps[:, None]
        be = s2.exps[None, :]
        p = al + be
        P = (al[..., None] * A + be[..., None] * B) / p[..., None]
        AB2 = float(np.dot(A - B, A - B))
        K = np.exp(-(al * be / p) * AB2)
        XPA = P - A
        XPB = P - B
        E = [e_coeffs(s1.l + 2, s2.l + 2, p, XPA[:, :, d], XPB[:, :, d])
             for d in range(3)]
        # contraction coefficients factorise over the bra/ket pair; the 3D
        # coefficient is the product of the three 1D ones, so fold c_p c_q
        # into a single direction only.
        cprod = np.outer(s1.coefs, s2.coefs)
        for i in range(len(E[0])):
            for j in range(len(E[0][i])):
                E[0][i][j] = E[0][i][j] * cprod[..., None]
        data = dict(p=p, P=P, K=K, inv2p=0.5 / p, E=E,
                    l1=s1.l, l2=s2.l, A=A, B=B,
                    n1=s1.exps.size, n2=s2.exps.size)
        self._pairs[key] = data
        return data

    # -- one electron ---------------------------------------------------
    def _ov_cart(self, i: int, j: int) -> np.ndarray:
        s1, s2 = self.mol.shells[i], self.mol.shells[j]
        d = self.pair(i, j)
        pref = (np.pi / d["p"]) ** 1.5 * d["K"]
        E = d["E"]
        out = np.zeros((s1.ncart, s2.ncart))
        for a, pa in enumerate(CART_POWERS[s1.l]):
            for b, pb in enumerate(CART_POWERS[s2.l]):
                out[a, b] = (pref * E[0][pa[0]][pb[0]][..., 0]
                             * E[1][pa[1]][pb[1]][..., 0]
                             * E[2][pa[2]][pb[2]][..., 0]).sum()
        return out

    def _kin_cart(self, i: int, j: int) -> np.ndarray:
        """Kinetic energy block: -1/2 <a| grad^2 |b> (derivative form)."""
        s1, s2 = self.mol.shells[i], self.mol.shells[j]
        d = self.pair(i, j)
        pref = (np.pi / d["p"]) ** 1.5 * d["K"]
        E = d["E"]
        be = s2.exps[None, :]

        def pov(pa, pb):
            return (pref * E[0][pa[0]][pb[0]][..., 0]
                    * E[1][pa[1]][pb[1]][..., 0]
                    * E[2][pa[2]][pb[2]][..., 0])

        out = np.zeros((s1.ncart, s2.ncart))
        for a, pa in enumerate(CART_POWERS[s1.l]):
            for b, pb in enumerate(CART_POWERS[s2.l]):
                val = 0.0
                for dirn in range(3):
                    ip, jp = list(pa), list(pb)
                    jj = jp[dirn]
                    term = -2.0 * be * (2 * jj + 1) * pov(ip, jp)
                    if jj >= 2:
                        lo = list(pb)
                        lo[dirn] -= 2
                        term = term + jj * (jj - 1) * pov(ip, lo)
                    hi = list(pb)
                    hi[dirn] += 2
                    term = term + 4.0 * be ** 2 * pov(ip, hi)
                    val = val + term.sum()
                out[a, b] = -0.5 * val
        return out

    def _nuc_cart(self, i: int, j: int) -> np.ndarray:
        s1, s2 = self.mol.shells[i], self.mol.shells[j]
        d = self.pair(i, j)
        p = d["p"]
        P = d["P"]
        E = d["E"]
        W = s1.l + s2.l + 1
        ncb = s2.ncart
        Cc = s1.ncart * ncb
        nq = p.size
        out = np.zeros((s1.ncart, ncb))
        G = []
        for dirn in range(3):
            G1 = np.zeros((Cc, nq, W))
            for a, pa in enumerate(CART_POWERS[s1.l]):
                for b, pb in enumerate(CART_POWERS[s2.l]):
                    G1[a * ncb + b] = E[dirn][pa[dirn]][pb[dirn]][..., :W].reshape(nq, W)
            G.append(G1)
        pflat = p.reshape(nq)
        for iat in range(self.mol.natom):
            Z = self.mol.charges[iat]
            cen = self.mol.coords[iat]
            X = (P[..., 0] - cen[0]).reshape(nq)
            Y = (P[..., 1] - cen[1]).reshape(nq)
            Zc = (P[..., 2] - cen[2]).reshape(nq)
            val = deriv_sum(G[0], G[1], G[2], pflat, X, Y, Zc)
            pref = (-Z * (2.0 * np.pi / pflat) * d["K"].reshape(nq))
            out += (val * pref[None, :]).sum(axis=1).reshape(s1.ncart, ncb)
        return out

    def one_electron(self):
        """Return (S, T, V) in the spherical AO basis."""
        mol = self.mol
        n = mol.nao
        S = np.zeros((n, n))
        T = np.zeros((n, n))
        V = np.zeros((n, n))
        nsh = len(mol.shells)
        for i in range(nsh):
            for j in range(i, nsh):
                si, sj = mol.shells[i], mol.shells[j]
                for dest, fn in ((S, self._ov_cart), (T, self._kin_cart),
                                 (V, self._nuc_cart)):
                    blk = si.transf @ fn(i, j) @ sj.transf.T
                    dest[si.sstart:si.sstart + si.nsph,
                         sj.sstart:sj.sstart + sj.nsph] = blk
                    if i != j:
                        dest[sj.sstart:sj.sstart + sj.nsph,
                             si.sstart:si.sstart + si.nsph] = blk.T
        return S, T, V

    # -- two electron ----------------------------------------------------
    def _pair_component_E(self, i, j):
        """E coefficients by cartesian component: 3 arrays (na, nb, n1, n2, W)."""
        s1, s2 = self.mol.shells[i], self.mol.shells[j]
        d = self.pair(i, j)
        E = d["E"]
        n1, n2 = d["n1"], d["n2"]
        wneed = s1.l + s2.l + 1
        out = []
        for dirn in range(3):
            arr = np.zeros((s1.ncart, s2.ncart, n1, n2, wneed))
            for a, pa in enumerate(CART_POWERS[s1.l]):
                for b, pb in enumerate(CART_POWERS[s2.l]):
                    arr[a, b] = E[dirn][pa[dirn]][pb[dirn]][..., :wneed]
            out.append(arr)
        return out

    def _eri_block(self, i: int, j: int, k: int, l: int, sph: bool = True):
        mol = self.mol
        sh = mol.shells
        s1, s2, s3, s4 = sh[i], sh[j], sh[k], sh[l]
        d12 = self.pair(i, j)
        d34 = self.pair(k, l)
        p, q = d12["p"], d34["p"]
        P, Q = d12["P"], d34["P"]

        pp = p[:, :, None, None]
        qq = q[None, None, :, :]
        rho = pp * qq / (pp + qq)
        X = P[:, :, None, None, 0] - Q[None, None, :, :, 0]
        Y = P[:, :, None, None, 1] - Q[None, None, :, :, 1]
        Z = P[:, :, None, None, 2] - Q[None, None, :, :, 2]
        pref = (TWO_PI_52 / (pp * qq * np.sqrt(pp + qq))
                * d12["K"][:, :, None, None] * d34["K"][None, None, :, :])

        M = s1.l + s2.l + s3.l + s4.l + 1
        nca, ncb, ncc, ncd = s1.ncart, s2.ncart, s3.ncart, s4.ncart
        Cc = nca * ncb * ncc * ncd
        Pn = rho.size

        E12 = self._pair_component_E(i, j)
        E34 = self._pair_component_E(k, l)
        G = []
        for dirn in range(3):
            G1 = E12[dirn].reshape(nca * ncb, -1, E12[dirn].shape[-1])
            G2 = E34[dirn].reshape(ncc * ncd, -1, E34[dirn].shape[-1])
            # primitive axes must stay separate: (C1,1,nq12,1,W) x (1,C2,1,nq34,W)
            fold = _fold_bra(G1[:, None, :, None, :], G2[None, :, None, :, :], M)
            G.append(fold.reshape(Cc, Pn, M))

        val = deriv_sum(G[0], G[1], G[2], rho.reshape(Pn),
                        X.reshape(Pn), Y.reshape(Pn), Z.reshape(Pn))
        block = (val * pref.reshape(1, Pn)).sum(axis=1).reshape(nca, ncb, ncc, ncd)
        if not sph:
            return block
        # transf is (nsph, ncart): contract cartesian index k with second label
        return np.einsum("ijkl,Ii,Jj,Kk,Ll->IJKL", block,
                         s1.transf, s2.transf, s3.transf, s4.transf)

    def eri(self, verbose: bool = False) -> np.ndarray:
        mol = self.mol
        n = mol.nao
        out = np.zeros((n, n, n, n))
        sh = mol.shells
        nsh = len(sh)
        pairs = [(i, j) for i in range(nsh) for j in range(i, nsh)]
        nq = 0
        for pi, (i, j) in enumerate(pairs):
            for pk in range(pi, len(pairs)):
                k, l = pairs[pk]
                blk = self._eri_block(i, j, k, l)
                self._put(out, (i, j, k, l), blk)
                self._put(out, (j, i, k, l), blk.transpose(1, 0, 2, 3))
                self._put(out, (i, j, l, k), blk.transpose(0, 1, 3, 2))
                self._put(out, (j, i, l, k), blk.transpose(1, 0, 3, 2))
                self._put(out, (k, l, i, j), blk.transpose(2, 3, 0, 1))
                self._put(out, (l, k, i, j), blk.transpose(3, 2, 0, 1))
                self._put(out, (k, l, j, i), blk.transpose(2, 3, 1, 0))
                self._put(out, (l, k, j, i), blk.transpose(3, 2, 1, 0))
                nq += 1
        if verbose:
            print(f"  [{nq} shell quartets]")
        return out

    def _put(self, dest, idx, blk):
        sh = self.mol.shells
        sl = tuple(slice(sh[t].sstart, sh[t].sstart + sh[t].nsph) for t in idx)
        dest[sl] = blk
